const I18nContext = createContext<I18nContextType | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  // 使用懒初始化避免 hydration 不匹配
  const [locale, setLocaleState] = useState<Locale>(() => {
    // 服务端渲染时返回默认值
    if (typeof window === "undefined") return "zh";
    // 客户端首次渲染时从 localStorage 读取
    const savedLocale = localStorage.getItem("wagmi-locale") as Locale;
    if (savedLocale && (savedLocale === "zh" || savedLocale === "en")) {
      return savedLocale;
    }
    const browserLang = navigator.language.toLowerCase();
    return browserLang.startsWith("en") ? "en" : "zh";
  });

  const setLocale = (newLocale: Locale) => {
    setLocaleState(newLocale);
    if (typeof window !== "undefined") {
      localStorage.setItem("wagmi-locale", newLocale);
    }
  };

  const t = (key: string): string => {
    return translations[locale][key] || key;
  };

  return (
    <I18nContext.Provider value={{ locale, setLocale, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error("useI18n must be used within I18nProvider");
  }
  return context;
}

// 语言切换组件
export function LanguageSwitcher({ className = "" }: { className?: string }) {
  const { locale, setLocale } = useI18n();

  return (
    <button
      onClick={() => setLocale(locale === "zh" ? "en" : "zh")}
      className={`px-3 py-1.5 bg-white/5 border border-white/10 rounded-lg text-sm text-gray-300 hover:bg-white/10 hover:text-white transition ${className}`}
    >
      {locale === "zh" ? "EN" : "中文"}
    </button>
  );
}
